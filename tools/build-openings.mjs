// Build data/openings.js from the Lichess chess-openings TSV files (CC0).
// Usage: node tools/build-openings.mjs
// Source: https://github.com/lichess-org/chess-openings (copied to tools/data/openings).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { Chess } from 'chess.js';
import { positionKey } from '../src/openings.js';

const dir = new URL('./data/openings/', import.meta.url);
const table = {};
let rows = 0;
for (const file of readdirSync(dir)
  .filter(f => f.endsWith('.tsv'))
  .sort()) {
  const lines = readFileSync(new URL(file, dir), 'utf8').trim().split('\n').slice(1);
  for (const line of lines) {
    const [eco, name, pgn] = line.split('\t');
    const g = new Chess();
    g.loadPgn(pgn);
    const key = positionKey(g.fen());
    // Several lines can reach one position; keep the shortest (most general) name.
    if (!table[key] || name.length < table[key].split('|')[1].length) table[key] = `${eco}|${name}`;
    rows++;
  }
}
const body = Object.entries(table)
  .map(([k, v]) => `${JSON.stringify(k)}:${JSON.stringify(v)}`)
  .join(',\n');
writeFileSync(
  new URL('../data/openings.js', import.meta.url),
  `// Generated by tools/build-openings.mjs from the Lichess chess-openings table (CC0). Do not edit.\n// Keys are positionKey() hashes of each named position.\nexport const OPENING_TABLE = {\n${body},\n};\n`,
);
console.log(`${rows} lines, ${Object.keys(table).length} positions`);
